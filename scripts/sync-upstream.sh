#!/usr/bin/env bash
# 同步 boypt/openssh-deb 的最新 release：
#   1. 下载上游 release 中所有匹配的 .tar.gz 资产
#   2. 解压并清除非 deb 文件
#   3. 注入本仓库的 universal-install.sh
#   4. 重新打包为同名 .tgz
#   5. 创建/更新本仓库的 GitHub Release 并上传 assets
#
# 依赖：gh、bash、tar、md5sum、sha256sum
set -euo pipefail

UPSTREAM_REPO="${UPSTREAM_REPO:-boypt/openssh-deb}"
TARGET_REPO="${TARGET_REPO:?TARGET_REPO is required}"
UNIVERSAL_INSTALL="${UNIVERSAL_INSTALL:-universal-install.sh}"
ASSET_PATTERN="${ASSET_PATTERN:-openssh-v*-*.tar.gz}"
FORCE="${FORCE:-false}"
DRY_RUN="${DRY_RUN:-false}"
UPSTREAM_TAG="${UPSTREAM_TAG:-}"

if [ ! -f "$UNIVERSAL_INSTALL" ]; then
  echo "ERROR: $UNIVERSAL_INSTALL not found" >&2
  exit 1
fi

if [ -n "$UPSTREAM_TAG" ]; then
  TAG="$UPSTREAM_TAG"
else
  TAG=$(gh api "repos/${UPSTREAM_REPO}/releases/latest" --jq .tag_name)
fi

if [ -z "$TAG" ] || [ "$TAG" = "null" ]; then
  echo "ERROR: could not resolve upstream release tag" >&2
  exit 1
fi

echo "Upstream: ${UPSTREAM_REPO}@${TAG}"
echo "Target:   ${TARGET_REPO}"
echo "Pattern:  ${ASSET_PATTERN}"

if [ "$DRY_RUN" != "true" ] && gh release view "$TAG" --repo "$TARGET_REPO" >/dev/null 2>&1 && [ "$FORCE" != "true" ]; then
  echo "Release ${TAG} already exists in ${TARGET_REPO}; nothing to do."
  exit 0
fi

rm -rf upstream work dist
mkdir -p upstream work dist

mapfile -t ALL_ASSETS < <(gh release view "$TAG" --repo "$UPSTREAM_REPO" --json assets --jq '.assets[].name')
ASSETS=()
for asset in "${ALL_ASSETS[@]}"; do
  # shellcheck disable=SC2053
  if [[ "$asset" == $ASSET_PATTERN ]]; then
    ASSETS+=("$asset")
  fi
done

if [ "${#ASSETS[@]}" -eq 0 ]; then
  echo "ERROR: no upstream assets match pattern ${ASSET_PATTERN}" >&2
  exit 1
fi

for asset in "${ASSETS[@]}"; do
  echo "Downloading ${asset}..."
  ok=false
  for attempt in 1 2 3; do
    rm -f "upstream/${asset}"
    if gh release download "$TAG" \
      --repo "$UPSTREAM_REPO" \
      --pattern "$asset" \
      --dir upstream \
      --clobber; then
      ok=true
      break
    fi
    echo "::warning::download failed for ${asset} (attempt ${attempt}/3)"
    sleep 3
  done
  if [ "$ok" != "true" ]; then
    echo "::warning::could not download ${asset}; skipping"
    rm -f "upstream/${asset}"
  fi
done

found=0
for archive in upstream/*.tar.gz; do
  [ -f "$archive" ] || continue

  name=$(basename "$archive" .tar.gz)
  echo "Building ${name}.tgz from ${archive}..."

  if [ ! -s "$archive" ] || ! tar -tzf "$archive" >/dev/null 2>&1; then
    echo "ERROR: invalid archive: ${archive}" >&2
    exit 1
  fi

  tmp=$(mktemp -d)
  tar -xzf "$archive" -C "$tmp"
  if [ -d "$tmp/$name" ]; then
    src="$tmp/$name"
  else
    # 上游有的版本没有顶层目录，deb 直接在包根目录
    src=$(find "$tmp" -mindepth 1 -maxdepth 1 -type d -print -quit)
    if [ -z "$src" ]; then
      src="$tmp"
    fi
  fi
  if [ ! -d "$src" ]; then
    echo "ERROR: cannot find payload directory in ${archive}" >&2
    exit 1
  fi

  mkdir -p "work/$name"
  cp -a "$src"/. "work/$name"/
  rm -rf "$tmp"

  # 只保留 deb，移除上游自带的 install.sh 等杂项
  find "work/$name" -mindepth 1 -maxdepth 1 ! -name '*.deb' -exec rm -rf {} +

  count=$(find "work/$name" -maxdepth 1 -name '*.deb' | wc -l | tr -d ' ')
  if [ "$count" -eq 0 ]; then
    echo "ERROR: ${name} contains no deb files" >&2
    exit 1
  fi
  if [ "$count" -ne 5 ]; then
    echo "::warning::${name} contains ${count} deb files (expected 5)"
  fi

  cp "$UNIVERSAL_INSTALL" "work/$name/install.sh"
  chmod 755 "work/$name/install.sh"
  bash -n "work/$name/install.sh"

  expected_md5=$(md5sum "$UNIVERSAL_INSTALL" | awk '{print $1}')
  actual_md5=$(md5sum "work/$name/install.sh" | awk '{print $1}')
  if [ "$expected_md5" != "$actual_md5" ]; then
    echo "ERROR: install.sh md5 mismatch in ${name}" >&2
    exit 1
  fi

  tar -czf "dist/${name}.tgz" -C work "$name"
  found=$((found + 1))
done

if [ "$found" -eq 0 ]; then
  echo "ERROR: no packages were built" >&2
  exit 1
fi

cd dist
: > SHA256SUMS
for f in *.tgz; do
  hash=$(sha256sum "$f" | awk '{print $1}')
  echo "${hash}  ${f}" >> SHA256SUMS
done
cd ..

{
  echo "## Upstream"
  echo ""
  echo "- Repository: \`${UPSTREAM_REPO}\`"
  echo "- Release: \`${TAG}\`"
  echo ""
  echo "## Assets"
  echo ""
  echo "| File | SHA256 |"
  echo "|------|--------|"
  while read -r hash file; do
    echo "| \`${file}\` | \`${hash}\` |"
  done < dist/SHA256SUMS
  echo ""
  echo "Generated by GitHub Actions. \`universal-install.sh\` has been injected into every tgz."
} > release-notes.md

cat release-notes.md

if [ "$DRY_RUN" = "true" ]; then
  echo "DRY_RUN: built assets in dist/, skipping publish."
  ls -lh dist/
  exit 0
fi

if gh release view "$TAG" --repo "$TARGET_REPO" >/dev/null 2>&1; then
  gh release upload "$TAG" dist/*.tgz dist/SHA256SUMS \
    --repo "$TARGET_REPO" --clobber
else
  gh release create "$TAG" dist/*.tgz dist/SHA256SUMS \
    --repo "$TARGET_REPO" \
    --title "OpenSSH ${TAG}" \
    --notes-file release-notes.md
fi

echo "Published ${TAG} to ${TARGET_REPO}."
